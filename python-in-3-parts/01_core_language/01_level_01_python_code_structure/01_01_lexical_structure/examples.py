# Lines and Indentation
x = 10
if x > 5:
    print("large")

# Character Sets
message = "단백질 분석"
print(message)

# Tokens
x = 10 + 20
print(x)

# Identifiers
protein_count = 100
sample_1 = "control"
print(protein_count, sample_1)

# Keywords
if True:
    print("yes")

# Operators
x, y = 10, 3
print(x + y)
print(x > y)

# Delimiters
values = [10, 20, 30]
if values:
    print(values[0])

# Literals
count = 10
name = "DNA"
values = [1, 2, 3]
print(count, name, values)
